package antcolony.algorithm;

/** Параметры муравьиного алгоритма. Их можно менять во время работы программы. */
public class Parameters {

    /** alpha — значимость феромона при выборе пути. */
    public double alpha = 1.5;
    /** beta — значимость расстояния между узлами при выборе пути. */
    public double beta = 3.0;
    /** rho — коэффициент обновления и испарения феромона (0 < rho < 1). */
    public double rho = 0.3;
    /** Q — количество феромона, которое муравей распределяет по своему маршруту. */
    public double q = 100.0;
    /**
     * Начальное количество феромона на каждом пути. Чем оно больше по сравнению с Q / L,
     * тем дольше муравьи в начале ходят по всем дорогам случайно.
     */
    public double initialPheromone = 5.0;
    /**
     * «Элитные муравьи»: в каждом цикле лучший найденный маршрут дополнительно подкрепляется
     * феромоном. Ускоряет схождение всех муравьёв к одному маршруту.
     * false — классическая «Муравьиная система» без элиты.
     */
    public boolean elitist = true;
    /** Количество муравьёв в колонии. */
    public int antCount = 10;
}
